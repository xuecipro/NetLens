package com.opensource.netlens.util

object FreqChannel {
    fun channelOf(freqMhz: Int): Int = when {
        freqMhz in 2412..2472 -> (freqMhz - 2412) / 5 + 1
        freqMhz == 2484 -> 14
        freqMhz in 5000..5900 -> (freqMhz - 5000) / 5
        freqMhz in 5955..7115 -> (freqMhz - 5955) / 5 + 1
        else -> 0
    }

    fun bandOf(freqMhz: Int): com.opensource.netlens.data.model.Band = when {
        freqMhz in 2400..2500 -> com.opensource.netlens.data.model.Band.BAND_24
        freqMhz in 4900..5900 -> com.opensource.netlens.data.model.Band.BAND_5
        freqMhz in 5925..7125 -> com.opensource.netlens.data.model.Band.BAND_6
        else -> com.opensource.netlens.data.model.Band.UNKNOWN
    }

    fun widthOf(widthMhz: Int?): Int? = widthMhz

    /** 2.4 GHz non-overlapping classic set */
    val classic24 = listOf(1, 6, 11)
}

object Formatters {
    fun rssiLabel(rssi: Int): String = "$rssi dBm"

    fun mbps(value: Double): String = when {
        value >= 100 -> String.format("%.0f", value)
        value >= 10 -> String.format("%.1f", value)
        else -> String.format("%.2f", value)
    }

    fun ms(value: Double): String = String.format("%.1f", value)

    fun percent(value: Double): String = String.format("%.1f", value)

    fun macVendor(mac: String): String {
        val prefix = mac.replace(":", "").replace("-", "").uppercase().take(6)
        return OuiDb.lookup(prefix)
    }

    fun ipToInt(ip: String): Int {
        val parts = ip.split(".")
        if (parts.size != 4) return 0
        var r = 0
        for (p in parts) {
            val v = p.toIntOrNull() ?: return 0
            r = (r shl 8) or (v and 0xFF)
        }
        return r
    }

    fun intToIp(value: Int): String {
        return listOf(
            (value ushr 24) and 0xFF,
            (value ushr 16) and 0xFF,
            (value ushr 8) and 0xFF,
            value and 0xFF
        ).joinToString(".")
    }

    fun subnetCandidates(ip: String, prefixLength: Int = 24, limit: Int = 254): List<String> {
        val base = ipToInt(ip)
        if (base == 0) return emptyList()
        val network = base and 0xFFFFFF00.toInt()
        val out = ArrayList<String>(limit)
        for (i in 1..minOf(254, limit)) {
            out += intToIp(network or i)
        }
        return out
    }
}

