object WifiStandards {
    fun fromScan(frequencyMhz: Int, capabilities: String, linkSpeedMbps: Int?): String {
        val cap = capabilities.uppercase()
        return when {
            "802.11BE" in cap || linkSpeedMbps?.let { it >= 2000 } == true -> "WiFi 7 / 802.11be"
            "802.11AX" in cap || frequencyMhz > 5925 -> "WiFi 6 / 802.11ax"
            "802.11AC" in cap || frequencyMhz in 5000..5900 -> "WiFi 5 / 802.11ac"
            "802.11N" in cap || (linkSpeedMbps ?: 0) >= 72 -> "WiFi 4 / 802.11n"
            else -> "WiFi legacy"
        }
    }

    fun fromLinkSpeed(linkSpeedMbps: Int, frequencyMhz: Int): String = when {
        linkSpeedMbps >= 2000 -> "WiFi 7"
        linkSpeedMbps >= 600 || frequencyMhz > 5925 -> "WiFi 6/6E"
        linkSpeedMbps >= 433 || frequencyMhz in 5000..5900 -> "WiFi 5"
        linkSpeedMbps >= 72 -> "WiFi 4"
        else -> "Legacy"
    }
}

object SecurityParser {
    fun parse(capabilities: String): com.opensource.netlens.data.model.SecurityType {
        val c = capabilities.uppercase()
        return when {
            "WEP" in c -> com.opensource.netlens.data.model.SecurityType.WEP
            "EAP" in c -> com.opensource.netlens.data.model.SecurityType.ENTERPRISE
            "WPA3" in c && "WPA2" in c -> com.opensource.netlens.data.model.SecurityType.WPA2_WPA3
            "WPA3" in c || "SAE" in c -> com.opensource.netlens.data.model.SecurityType.WPA3
            "WPA2" in c -> com.opensource.netlens.data.model.SecurityType.WPA2
            "WPA" in c -> com.opensource.netlens.data.model.SecurityType.WPA
            "ESS" in c && "[ESS]" in c && "WPA" !in c && "WEP" !in c -> com.opensource.netlens.data.model.SecurityType.OPEN
            c.isBlank() || c == "[ESS]" -> com.opensource.netlens.data.model.SecurityType.OPEN
            else -> com.opensource.netlens.data.model.SecurityType.UNKNOWN
        }
    }
}
